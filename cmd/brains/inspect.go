package main

import (
	"archive/zip"
	"strings"
)

// inspectZip lists parts and scans for AI-provenance markers.
// Read-only, never mutates the file.
func inspectZip(path string) ([]string, []string) {
	zr, err := zip.OpenReader(path)
	if err != nil {
		return nil, []string{"not-a-zip:" + err.Error()}
	}
	defer zr.Close()
	parts := []string{}
	hits := []string{}
	markers := []string{"python-docx", "excelize", "openpyxl", "Codex", "OpenAI", "generated by", "unioffice"}
	for _, f := range zr.File {
		parts = append(parts, f.Name)
		// only scan small xml parts (skip media)
		if strings.HasSuffix(f.Name, ".xml") || strings.HasSuffix(f.Name, ".rels") {
			rc, err := f.Open()
			if err != nil {
				continue
			}
			buf := make([]byte, 0, 65536)
			tmp := make([]byte, 8192)
			for {
				n, rerr := rc.Read(tmp)
				if n > 0 {
					buf = append(buf, tmp[:n]...)
					if len(buf) > 60000 {
						break
					}
				}
				if rerr != nil {
					break
				}
			}
			rc.Close()
			s := string(buf)
			low := strings.ToLower(s)
			for _, m := range markers {
				if strings.Contains(low, strings.ToLower(m)) {
					hits = append(hits, f.Name+":contains:"+m)
				}
			}
		}
	}
	if len(hits) == 0 {
		hits = []string{}
	}
	return parts, hits
}
